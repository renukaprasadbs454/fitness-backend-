const router = require("express").Router();
const { authenticate } = require("../../middlewares/auth.middleware");
const { requireRole } = require("../../middlewares/role.middleware");
const { ROLES } = require("../../constants/roles");
const controller = require("../../controllers/privacy.controller");
router.use(authenticate, requireRole(ROLES.ADMIN));
router.get("/overview", controller.adminOverview);
router.get("/documents", controller.adminLegalDocuments);
router.put("/documents", controller.adminLegalDocuments);
router.get("/requests", controller.adminList("requests"));
router.patch("/requests/:id", controller.adminUpdate("requests"));
router.get("/grievances", controller.adminList("grievances"));
router.patch("/grievances/:id", controller.adminUpdate("grievances"));
router.get("/audit", controller.adminList("audit"));
router.get("/processors", controller.processors);
router.put("/processors", controller.processors);
router.get("/retention", controller.retentionPolicies);
router.put("/retention", controller.retentionPolicies);
router.post("/retention/dry-run", controller.retentionDryRun);
router.get("/breaches", controller.breaches);
router.post("/breaches", controller.breaches);
router.patch("/breaches/:id", controller.updateBreach);
module.exports = router;
